#!/usr/bin/env python3
"""Turns the pipeline layout in make_pipeline_image.py into a React component (app/components/PipelineDiagram.tsx):
real SVG lines and text in the page's own colour and font, so the diagram is part of the website, not a picture.
Run: python3 video/diagram/make_pipeline_svg.py"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(HERE, "make_pipeline_image.py")).read().split("# ---- render ----")[0]
ns = {}
exec(src, ns)  # builds `lines` (direction bits per cell) and `text` (one character per cell)
lines, text, COLS, ROWS = ns["lines"], ns["text"], ns["COLS"], ns["ROWS"]
E, S = ns["E"], ns["S"]

CW, CH, PAD = 11, 23, 14
W, H = COLS * CW + PAD * 2, ROWS * CH + PAD * 2
cx = lambda x: PAD + x * CW + CW / 2
cy = lambda y: PAD + y * CH + CH / 2

# ---- line segments, merged into long runs ----
segs = []
for y in range(ROWS):  # horizontal runs
    x = 0
    while x < COLS:
        if lines.get((x, y), 0) & E:
            x0 = x
            while lines.get((x, y), 0) & E:
                x += 1
            segs.append((cx(x0), cy(y), cx(x), cy(y)))
        else:
            x += 1
for x in range(COLS):  # vertical runs
    y = 0
    while y < ROWS:
        if lines.get((x, y), 0) & S:
            y0 = y
            while lines.get((x, y), 0) & S:
                y += 1
            segs.append((cx(x), cy(y0), cx(x), cy(y)))
        else:
            y += 1
path = " ".join(f"M{a:.1f} {b:.1f}L{c:.1f} {d:.1f}" for a, b, c, d in segs)

# ---- arrows and text runs ----
arrows = []
runs = []
for y in range(ROWS):
    x = 0
    while x < COLS:
        ch = text.get((x, y))
        if ch in ("▼", "▶"):
            arrows.append((ch, x, y))
            x += 1
        elif ch:
            x0, s = x, ""
            while text.get((x, y)) and text[(x, y)] not in ("▼", "▶"):
                s += text[(x, y)]
                x += 1
            runs.append((x0, y, s))
        else:
            x += 1

poly = []
for ch, x, y in arrows:
    a, b = cx(x), cy(y)
    pts = [(a - 6, b - 5), (a + 6, b - 5), (a, b + 6)] if ch == "▼" else [(a - 5, b - 6), (a - 5, b + 6), (a + 6, b)]
    poly.append(" ".join(f"{p:.1f},{q:.1f}" for p, q in pts))

import re

texts = []
for x0, y, s in runs:
    # SVG collapses runs of spaces, which would throw off the spacing. So each stretch of words joined by single
    # spaces is its own <text>, placed at its exact column, with no leading or trailing space.
    for m in re.finditer(r"\S+(?: \S+)*", s):
        seg = m.group(0)
        texts.append(f'        <text x="{PAD + (x0 + m.start()) * CW:.1f}" y="{PAD + y * CH + 16.5:.1f}" textLength="{len(seg) * CW}" lengthAdjust="spacing">{seg}</text>')

tsx = f'''// Generated by video/diagram/make_pipeline_svg.py from the layout in make_pipeline_image.py. Do not edit by hand.
// The structure of the project (the pipeline in docs/PLAN.md), drawn in the style of Otto's voice pipeline. It is real SVG
// in the page's own colour and font, so it follows light and dark mode and has no picture, card or border around it.

export function PipelineDiagram() {{
  return (
    <svg
      viewBox="0 0 {W} {H}"
      role="img"
      aria-label="The Airlock pipeline. Voice goes through ElevenLabs Scribe, and typed or iMessage text goes straight, into the input router, then Gemini for intent and function tools. Four tools follow: resolve, contract auditor, send and explain. Then the risk gate, the context builder, Gemini's response and the output router, which answers in the GUI with voice, or by iMessage text. A live event log streams the audit stages to the dashboard."
      className="h-auto w-full text-foreground"
    >
      <path d="{path}" fill="none" stroke="currentColor" strokeWidth={{1.6}} strokeLinecap="square" />
      <g fill="currentColor">
{chr(10).join(f'        <polygon points="{p}" />' for p in poly)}
      </g>
      <g fill="currentColor" fontSize={{16.5}} fontFamily="var(--font-geist-mono), ui-monospace, Menlo, monospace">
{chr(10).join(texts)}
      </g>
    </svg>
  );
}}
'''
out = os.path.join(HERE, "..", "..", "app", "components", "PipelineDiagram.tsx")
open(out, "w").write(tsx)
print("wrote", os.path.normpath(out), f"{W}x{H}", len(segs), "line runs,", len(poly), "arrows,", len(texts), "text runs")
